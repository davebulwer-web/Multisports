export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;

const atlasCache = new Map();
const CHARS = Object.keys(G);

function atlasFor(color) {
  if (atlasCache.has(color)) return atlasCache.get(color);
  const c = document.createElement('canvas');
  c.width = CHARS.length * GLYPH_W;
  c.height = GLYPH_H;
  const x = c.getContext('2d');
  x.fillStyle = color;
  CHARS.forEach((ch, i) => {
    G[ch].split(',').forEach((row, y) => {
      for (let px = 0; px < 5; px++) if (row[px] === '#') x.fillRect(i * GLYPH_W + px, y, 1, 1);
    });
  });
  atlasCache.set(color, c);
  return c;
}

export function textWidth(str, scale = 1) {
  return Math.max(0, str.length * ADVANCE - 1) * scale;
}

/**
 * Draw text. opts: {color, shadow, align:'left'|'center'|'right', scale}
 * Lowercase is drawn as uppercase.
 */
export function drawText(ctx, str, x, y, opts = {}) {
  const { color = '#ffffff', shadow = '#000000', align = 'left', scale = 1 } = opts;
  str = String(str).toUpperCase();
  if (align === 'center') x -= Math.floor(textWidth(str, scale) / 2);
  else if (align === 'right') x -= textWidth(str, scale);
  x = Math.round(x); y = Math.round(y);
  if (shadow) drawRaw(ctx, str, x + scale, y + scale, shadow, scale);
  drawRaw(ctx, str, x, y, color, scale);
}

function drawRaw(ctx, str, x, y, color, scale) {
  const atlas = atlasFor(color);
  for (let i = 0; i < str.length; i++) {
    let idx = CHARS.indexOf(str[i]);
    if (idx < 0) idx = CHARS.indexOf('?');
    ctx.drawImage(atlas, idx * GLYPH_W, 0, GLYPH_W, GLYPH_H, x + i * ADVANCE * scale, y, GLYPH_W * scale, GLYPH_H * scale);
  }
}
